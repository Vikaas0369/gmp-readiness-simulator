def _fmt_money(x):
    return f"${x:,.0f}"


def _fmt_money_compact(x):
    """
    Compact money format for tight spaces (e.g., dashboard tiles).
    Uses K for thousands, M for millions, B for billions.
    """
    if x is None:
        return "N/A"
    abs_x = abs(x)
    if abs_x >= 1_000_000_000:
        return f"${x/1_000_000_000:.1f}B"
    if abs_x >= 10_000_000:
        return f"${x/1_000_000:.1f}M"
    if abs_x >= 1_000_000:
        return f"${x/1_000_000:.2f}M"
    if abs_x >= 1_000:
        return f"${x/1_000:,.0f}K"
    return f"${x:,.0f}"


