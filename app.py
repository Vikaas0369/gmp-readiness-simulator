def _make_tagline(explanation):
    for sep in [". ", " — ", " - ", ": "]:
        if sep in explanation:
            first = explanation.split(sep, 1)[0]
            if 10 < len(first) < 90:
                return first
    if len(explanation) <= 75:
        return explanation
    truncated = explanation[:75]
    last_space = truncated.rfind(" ")
    if last_space > 30:
        truncated = truncated[:last_space]
    return truncated + "…"


def _wrap_text(text, max_chars=24, max_lines=3):
    words = text.split()
    lines = []
    current = ""
    for word in words:
        if len(word) > max_chars:
            if current:
                lines.append(current)
                current = ""
            while len(word) > max_chars:
                lines.append(word[:max_chars])
                word = word[max_chars:]
            current = word
            continue
        candidate = (current + " " + word).strip()
        if len(candidate) <= max_chars:
            current = candidate
        else:
            if current:
                lines.append(current)
            current = word
    if current:
        lines.append(current)
    if len(lines) > max_lines:
        lines = lines[:max_lines]
        last = lines[-1]
        if len(last) > max_chars - 1:
            last = last[:max_chars - 1].rstrip()
        lines[-1] = last + "…"
    return "<br>".join(lines)


